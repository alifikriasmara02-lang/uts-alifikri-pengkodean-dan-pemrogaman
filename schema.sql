-- Struktur database Voucher Kas Keluar
-- Jalankan di Supabase SQL Editor pada proyek yang sesuai.

CREATE TABLE IF NOT EXISTS public.chart_of_accounts (
    account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_code VARCHAR(20) NOT NULL UNIQUE,
    account_name VARCHAR(100) NOT NULL,
    normal_balance VARCHAR(10) NOT NULL
        CHECK (normal_balance IN ('DEBIT', 'CREDIT')),
    report_classification VARCHAR(30) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.journal_headers (
    header_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_date DATE NOT NULL,
    reference_no VARCHAR(50) NOT NULL UNIQUE,
    description TEXT,
    posting_status VARCHAR(20) NOT NULL DEFAULT 'DRAFT'
        CHECK (posting_status IN ('DRAFT', 'POSTED')),
    created_by TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    hash_checksum TEXT
);

CREATE TABLE IF NOT EXISTS public.journal_lines (
    line_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    header_id BIGINT NOT NULL
        REFERENCES public.journal_headers(header_id) ON DELETE RESTRICT,
    account_id BIGINT NOT NULL
        REFERENCES public.chart_of_accounts(account_id) ON DELETE RESTRICT,
    debit NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK (debit >= 0),
    credit NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK (credit >= 0),
    CHECK (NOT (debit = 0 AND credit = 0)),
    CHECK (debit = 0 OR credit = 0)
);

